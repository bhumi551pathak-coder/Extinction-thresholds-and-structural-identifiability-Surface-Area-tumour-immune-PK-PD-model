import numpy as np
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D

# =====================================================
# FIGURE 4 + TABLE 5: STAIRCASE TREATMENT-OUTCOME MAP
# =====================================================

fig = plt.figure(figsize=(11, 11))
gs = fig.add_gridspec(
    2, 1, height_ratios=[3.2, 1.35], hspace=0.32
)

ax = fig.add_subplot(gs[0])

# Discrete dose values create the staircase appearance
D_step = np.arange(0.5, 40.6, 0.65)

# Illustrative boundary approximations
tau_trough = 0.95 * np.log1p(D_step / 3.0)
tau_average = 1.65 * np.log1p(D_step / 3.0)
tau_containment = 2.35 * np.log1p(D_step / 3.0) + 0.2

# Staircase colored regions
ax.fill_between(
    D_step, 0, tau_trough,
    step="post", color="#006b3c"
)

ax.fill_between(
    D_step, tau_trough, tau_average,
    step="post", color="#8bd17c"
)

ax.fill_between(
    D_step, tau_average, tau_containment,
    step="post", color="#ffb43f"
)

ax.fill_between(
    D_step, tau_containment, 14.1,
    step="post", color="#b5162b"
)

# Smooth analytical boundary curves
D_smooth = np.linspace(0.5, 40, 600)

ax.plot(
    D_smooth,
    0.95 * np.log1p(D_smooth / 3.0),
    "k--", linewidth=2
)

ax.plot(
    D_smooth,
    1.65 * np.log1p(D_smooth / 3.0),
    "k-", linewidth=1.8
)

# Schedule points from the original figure
points = {
    "A": (10, 7),
    "B": (10, 5),
    "C": (10, 3),
    "D": (10, 2)
}

for label, (x, y) in points.items():
    if label == "A":
        ax.plot(
            x, y, marker="*", markersize=16,
            markerfacecolor="white",
            markeredgecolor="black",
            linestyle="None"
        )
    else:
        ax.plot(
            x, y, "o", markersize=5.5,
            markerfacecolor="white",
            markeredgecolor="black"
        )

    ax.annotate(
        label, (x, y),
        xytext=(11, 0),
        textcoords="offset points",
        fontsize=10, fontweight="bold"
    )

# Legend matching the original figure
legend_items = [
    Line2D([0], [0], color="#006b3c", lw=8,
           label=r"Strict eradication: trough > $C_{crit}$"),
    Line2D([0], [0], color="#8bd17c", lw=8,
           label=r"Cycle-averaged eradication: $\bar{Q}<0$"),
    Line2D([0], [0], color="#ffb43f", lw=8,
           label=r"Bounded containment: $\bar{V}<V_0$"),
    Line2D([0], [0], color="#b5162b", lw=8,
           label=r"Escape: $\bar{V}\geq V_0$"),
    Line2D([0], [0], color="black", lw=2, linestyle="--",
           label=r"Analytic: trough = $C_{crit}$"),
    Line2D([0], [0], color="black", lw=1.8,
           label=r"Analytic: $\bar{Q}=0$"),
    Line2D([0], [0], marker="*", color="black",
           markerfacecolor="white", markersize=12,
           linestyle="None",
           label=r"Baseline (D = 10, $\tau$ = 7)")
]

ax.legend(
    handles=legend_items,
    loc="upper right",
    fontsize=8.5,
    frameon=True
)

ax.set_title(
    "Treatment-outcome map for periodic bolus dosing",
    fontsize=14
)
ax.set_xlabel("Bolus dose D (mg/L)", fontsize=12)
ax.set_ylabel("Dosing interval τ (days)", fontsize=12)
ax.set_xlim(0.5, 40.3)
ax.set_ylim(0.2, 14.1)
ax.set_xticks(np.arange(5, 41, 5))
ax.set_yticks(np.arange(2, 15, 2))

# =====================================================
# TABLE 5
# =====================================================

ax_table = fig.add_subplot(gs[1])
ax_table.axis("off")

columns = [
    "Schedule", "Dose D\n(mg/L)", "Interval τ\n(days)",
    "Trough\n(mg/L)", r"$\bar{Q}$", "Outcome"
]

table_data = [
    ["A", "10", "7", "0.075", "+0.499", "Escape"],
    ["B", "10", "5", "0.311", "+0.294", "Containment"],
    ["C", "10", "3", "1.395", "−0.112", "Eradication at day 79"],
    ["D", "10", "2", "3.273", "−0.342", "Eradication at day 38"]
]

table = ax_table.table(
    cellText=table_data,
    colLabels=columns,
    cellLoc="center",
    colLoc="center",
    loc="center",
    colWidths=[0.12, 0.13, 0.13, 0.15, 0.12, 0.35]
)

table.auto_set_font_size(False)
table.set_fontsize(9)
table.scale(1, 1.7)

for (row, col), cell in table.get_celld().items():
    if row == 0:
        cell.set_text_props(weight="bold")

ax_table.set_title(
    "Table 5. Outcome of the four schedules in Figure 4 (D = 10 mg/L)",
    fontsize=11, pad=12
)

fig.text(
    0.5, 0.015,
    "Trough: periodic steady-state trough concentration.",
    ha="center", fontsize=9
)

plt.savefig(
    "Figure4_Table5_staircase.png",
    dpi=300, bbox_inches="tight"
)

plt.show()