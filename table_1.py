import sympy as sp
import numpy as np
import pandas as pd
from IPython.display import display

# =========================================================
# STRUCTURAL IDENTIFIABILITY ANALYSIS
# Tumor-Immune Model
# =========================================================

# 1. Define variables and parameters
V, E, E0 = sp.symbols('V E E0', positive=True)

a, b, rho, s, p, h, delta = sp.symbols(
    'a b rho s p h delta', positive=True
)

# 2. Define the model equations
dVdt = a*V**sp.Rational(2, 3) - b*V - rho*E*V
dEdt = s + p*V/(V + h) - delta*E

print("Tumor equation:")
display(sp.Eq(sp.Symbol('dV/dt'), dVdt))

print("Immune equation:")
display(sp.Eq(sp.Symbol('dE/dt'), dEdt))

# 3. Define identifiable parameter combinations
q_p = rho*p
beta_0 = b + rho*E0
q_0 = rho*s + delta*b

combinations = [
    a,
    h,
    delta,
    q_p,
    beta_0,
    q_0
]

combination_names = [
    "a",
    "h",
    "delta",
    "rho*p",
    "b + rho*E0",
    "rho*s + delta*b"
]

print("\nIdentifiable combinations for V(t)-only observations:")
for name, expression in zip(combination_names, combinations):
    print(name, "=", expression)

# 4. Calculate Jacobian matrix of the combinations
original_parameters = [
    a, b, rho, s, p, h, delta, E0
]

J = sp.Matrix(combinations).jacobian(original_parameters)

print("\nSymbolic Jacobian matrix:")
display(J)

# 5. Numerical rank at a generic positive parameter point
parameter_values = {
    a: 0.8,
    b: 0.02,
    rho: 0.015,
    s: 0.3,
    p: 0.5,
    h: 200.0,
    delta: 0.2,
    E0: 1.0
}

J_numeric = np.array(
    J.subs(parameter_values).evalf(),
    dtype=float
)

rank = np.linalg.matrix_rank(J_numeric)

print("\nJacobian matrix:")
display(pd.DataFrame(
    J_numeric,
    index=combination_names,
    columns=[str(x) for x in original_parameters]
))

print("Jacobian rank =", rank)
print("Number of original unknowns =", len(original_parameters))
print("Number of reported combinations =", len(combinations))

# 6. Structural identifiability summary
data = [
    ["a", "Identifiable", "Identifiable"],
    ["b", "Not individually identifiable", "Identifiable"],
    ["rho", "Not individually identifiable",
     "Identifiable"],
    ["s", "Not individually identifiable", "Identifiable"],
    ["p", "Not individually identifiable", "Identifiable"],
    ["h", "Identifiable", "Identifiable"],
    ["delta", "Identifiable", "Identifiable"],
    ["rho*s + delta*b", "Identifiable combination",
     "Not required"],
    ["rho*p", "Identifiable combination", "Not required"],
    ["b + rho*E0", "Identifiable combination",
     "Not required"],
    ["E0", "Not individually identifiable",
     "Identifiable (observed directly)"]
]

table = pd.DataFrame(
    data,
    columns=[
        "Parameter / combination",
        "V(t) only",
        "V(t), E(t) jointly"
    ]
)

print("\nStructural identifiability summary:")
display(table)

# 7. Save table as CSV in Google Colab
table.to_csv(
    "structural_identifiability_summary.csv",
    index=False
)

print("\nCSV table saved successfully.")

