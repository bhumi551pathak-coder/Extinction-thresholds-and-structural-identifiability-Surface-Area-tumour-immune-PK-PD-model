import numpy as np
import matplotlib.pyplot as plt

# ------------------------------------------------------------
# Figure 1: Classical VB, untreated tumor-immune, and complete
# PK-PD-tumor-immune model with weekly bolus dosing.
# Based on the equations and illustrative parameters in the manuscript.
# ------------------------------------------------------------

# Parameters (manuscript Section 4.2)
a = 0.8
b = 0.02
rho = 0.015
s = 0.3
p = 0.5
h = 200.0
delta = 0.2
k = 0.7
Emax = 1.5
EC50 = 2.0
hill_n = 2.0

V0 = 100.0
E0 = 1.0
C0_minus = 0.0

# Simulation settings
dt = 0.01
T_end = 400.0
t = np.arange(0.0, T_end + dt/2, dt)
N = len(t)
dose = 10.0
dose_times = np.arange(0.0, 57.0, 7.0)  # 0, 7, ..., 56 days
dose_indices = np.rint(dose_times / dt).astype(int)

def rk4_step(fun, y, step):
    k1 = np.asarray(fun(y), dtype=float)
    k2 = np.asarray(fun(y + 0.5 * step * k1), dtype=float)
    k3 = np.asarray(fun(y + 0.5 * step * k2), dtype=float)
    k4 = np.asarray(fun(y + step * k3), dtype=float)
    return y + (step / 6.0) * (k1 + 2*k2 + 2*k3 + k4)

# 1) Classical von Bertalanffy: dV/dt = a V^(2/3) - b V
V_classical = np.zeros(N)
V_classical[0] = V0

def rhs_classical(y):
    V = max(float(y[0]), 0.0)
    return np.array([a * V**(2/3) - b * V])

for i in range(N - 1):
    V_classical[i+1] = max(rk4_step(rhs_classical, np.array([V_classical[i]]), dt)[0], 0.0)

V_inf = (a / b)**3

# 2) Untreated tumor-immune system
# dV/dt = a V^(2/3) - bV - rho E V
# dE/dt = s + p V/(V+h) - delta E
Y_immune = np.zeros((N, 2))
Y_immune[0, :] = [V0, E0]

def rhs_immune(y):
    V, E = np.maximum(np.asarray(y, dtype=float), 0.0)
    dV = a * V**(2/3) - b*V - rho*E*V
    dE = s + p*V/(V+h) - delta*E
    return np.array([dV, dE])

for i in range(N - 1):
    yn = rk4_step(rhs_immune, Y_immune[i, :], dt)
    Y_immune[i+1, :] = np.maximum(yn, 0.0)

V_immune = Y_immune[:, 0]

# 3) Complete tumor-immune-PK-PD system.
# Between boluses: dC/dt = -kC.
# Q(C) = 1 - Emax*C^n/(EC50^n + C^n)
# dV/dt = a Q(C) V^(2/3) - bV - rho E V
# dE/dt = s + p V/(V+h) - delta E
Y_drug = np.zeros((N, 3))  # columns V, E, C
Y_drug[0, :] = [V0, E0, C0_minus + dose]

def rhs_complete(y):
    V, E, C = np.maximum(np.asarray(y, dtype=float), 0.0)
    Q = 1.0 - Emax * C**hill_n / (EC50**hill_n + C**hill_n)
    dV = a * Q * V**(2/3) - b*V - rho*E*V
    dE = s + p*V/(V+h) - delta*E
    dC = -k*C
    return np.array([dV, dE, dC])

dose_index_set = set(dose_indices.tolist())
for i in range(N - 1):
    yn = rk4_step(rhs_complete, Y_drug[i, :], dt)
    yn = np.maximum(yn, 0.0)

    # Numerical extinction threshold (only affects very small volumes)
    V_cell = 1e-6
    if yn[0] < V_cell:
        yn[0] = 0.0
    if Y_drug[i, 0] == 0.0:
        yn[0] = 0.0

    # Apply bolus at the newly reached time point, so the stored C value
    # at each dose time is the post-dose concentration.
    next_index = i + 1
    if next_index in dose_index_set:
        yn[2] += dose

    Y_drug[i+1, :] = yn

V_drug = Y_drug[:, 0]

# Calculate positive untreated tumor-immune equilibrium V*.
# E* = (s + p V/(V+h))/delta and
# a V^(-1/3) - b - rho E* = 0.
def equilibrium_residual(V):
    E_star = (s + p*V/(V+h)) / delta
    return a*V**(-1/3) - b - rho*E_star

lo, hi = 1e-6, 1e5
if equilibrium_residual(lo) * equilibrium_residual(hi) >= 0:
    raise RuntimeError("Could not bracket the positive immune equilibrium.")
for _ in range(200):
    mid = 0.5*(lo+hi)
    if equilibrium_residual(lo)*equilibrium_residual(mid) <= 0:
        hi = mid
    else:
        lo = mid
V_star = 0.5*(lo+hi)
E_star = (s + p*V_star/(V_star+h))/delta
C_crit = EC50 * (Emax - 1.0)**(-1.0/hill_n)

print(f"Classical equilibrium V_inf = {V_inf:.4f} mm^3")
print(f"Untreated tumor-immune equilibrium V* = {V_star:.4f} mm^3")
print(f"Immune equilibrium E* = {E_star:.6f} (10^6 cells)")
print(f"PD critical concentration Ccrit = {C_crit:.4f} mg/L")

# Plot
fig, ax = plt.subplots(figsize=(9, 5.4))
ax.semilogy(t, V_classical, 'b-', linewidth=1.8,
            label='Classical VB (no immune, no drug)')
ax.semilogy(t, V_immune, 'r--', linewidth=1.8,
            label='VB + immune, untreated')
ax.semilogy(t, V_drug, color='green', linestyle='-.', linewidth=1.8,
            label='VB + immune, weekly 10 mg/L bolus (9 doses)')

ax.axhline(V_inf, color='blue', linestyle=':', linewidth=1.1)
ax.axhline(V_star, color='orangered', linestyle=':', linewidth=1.1)
ax.axvline(56, color='gray', linestyle=':', linewidth=1.0)

ax.text(10, V_inf*1.08, f'$V_\\infty=(a/b)^3={V_inf:,.0f}$ mm$^3$',
        color='blue', fontsize=9, va='bottom')
ax.text(10, V_star*1.10, f'$V^*={V_star:.1f}$ mm$^3$',
        color='orangered', fontsize=9, va='bottom')
ax.text(59, 150, 'last dose', color='gray', fontsize=8)
ax.text(59, 115, '(day 56)', color='gray', fontsize=8)

ax.set_xlabel('Time (days)')
ax.set_ylabel('Tumor volume V(t) (mm$^3$)')
ax.set_title('Growth under the classical and extended models')
ax.set_xlim(0, T_end)
ax.set_ylim(70, 2e5)
ax.grid(True, which='both', alpha=0.25)
ax.legend(loc='lower right', fontsize=8)
fig.tight_layout()
plt.show()

