# =========================================================
# Plot 1: Ranked PRCC bar chart
# =========================================================

fig, ax = plt.subplots(figsize=(9, 6))

colors = [
    "steelblue" if value > 0 else "indianred"
    for value in df["PRCC"]
]

bars = ax.barh(
    df["Parameter"],
    df["PRCC"],
    color=colors
)

ax.axvline(0, color="black", linewidth=0.9)
ax.set_xlabel("Partial Rank Correlation Coefficient (PRCC)")
ax.set_ylabel("Parameter")
ax.set_title(
    r"PRCC of Tumor Volume $V(60)$ ($N=1024$, $\pm20\%$)"
)
ax.invert_yaxis()
ax.grid(axis="x", alpha=0.3)

for bar, value in zip(bars, df["PRCC"]):
    offset = 0.015 if value >= 0 else -0.015
    ax.text(
        value + offset,
        bar.get_y() + bar.get_height()/2,
        f"{value:+.3f}",
        va="center",
        ha="left" if value >= 0 else "right",
        fontsize=8
    )

plt.tight_layout()
plt.show()

# =========================================================
# Plot 2: Absolute PRCC sensitivity ranking
# =========================================================

ranked = df.sort_values(
    "PRCC",
    key=lambda x: x.abs(),
    ascending=True
)

fig, ax = plt.subplots(figsize=(8, 5.5))

ax.barh(
    ranked["Parameter"],
    ranked["PRCC"].abs()
)

ax.set_xlabel(r"Absolute PRCC, $|\mathrm{PRCC}|$")
ax.set_ylabel("Parameter")
ax.set_title("Parameter Importance Ranking")
ax.grid(axis="x", alpha=0.3)

plt.tight_layout()
plt.show()

