import numpy as np
import matplotlib.pyplot as plt

# ============================================================
# Numerical simulation: Tumor–Immune–Drug dynamics
# Weekly 10 mg/L bolus, doses at t = 0, 7, ..., 56 days
# RK4 numerical method
# ============================================================

# Model parameters
a = 0.8
b = 0.02
rho = 0.015
s = 0.3
p = 0.5
h = 200.0
delta = 0.2

k = 0.7
Emax = 1.5
EC50 = 2.0
hill_n = 2.0

V0 = 100.0
E0 = 1.0
Ccrit = 2.8284

dose = 10.0
dose_times = np.arange(0, 57, 7)

# Simulation grid
dt = 0.01
T = 60.0
t = np.arange(0, T + dt/2, dt)
N = len(t)

# State variables: V = tumor volume, E = immune cells, C = drug
Y = np.zeros((N, 3))
Y[0] = [V0, E0, dose]  # first bolus at t = 0

dose_indices = set(np.rint(dose_times / dt).astype(int))

def rhs(y):
    V, E, C = np.maximum(y, 0.0)

    # Drug pharmacodynamic effect
    Q = 1 - Emax * C**hill_n / (EC50**hill_n + C**hill_n)

    dV = a * V**(2/3) - b*V - rho*E*V - a*(1-Q)*V**(2/3)
    dE = s + p*V/(V+h) - delta*E
    dC = -k*C

    return np.array([dV, dE, dC])

def rk4_step(y, dt):
    k1 = rhs(y)
    k2 = rhs(y + dt*k1/2)
    k3 = rhs(y + dt*k2/2)
    k4 = rhs(y + dt*k3)
    return y + dt*(k1 + 2*k2 + 2*k3 + k4)/6

# Integrate the model and apply bolus doses
for i in range(N-1):
    ynew = rk4_step(Y[i], dt)
    ynew = np.maximum(ynew, 0.0)

    # Apply dose at the next grid point, after integrating to that time
    next_index = i + 1
    if next_index in dose_indices:
        ynew[2] += dose

    Y[next_index] = ynew

V = Y[:, 0]
E = Y[:, 1]
C = Y[:, 2]

# ============================================================
# Plot three panels
# ============================================================

fig, axes = plt.subplots(3, 1, figsize=(9, 8), sharex=True)
fig.suptitle(
    "Weekly 10 mg/L bolus, doses at t = 0, 7, ..., 56 d",
    fontsize=12
)

# (a) Tumor volume
axes[0].plot(t, V, color="blue", linewidth=1.5)
axes[0].set_title("(a) Tumour volume", fontsize=10)
axes[0].set_ylabel("V (mm³)")
axes[0].grid(True, alpha=0.25)

# (b) Immune effector cells
axes[1].plot(t, E, color="blue", linewidth=1.5)
axes[1].set_title("(b) Immune effector cells", fontsize=10)
axes[1].set_ylabel("E (10⁶ cells)")
axes[1].grid(True, alpha=0.25)

# (c) Drug concentration and critical threshold
axes[2].plot(t, C, color="blue", linewidth=1.4)
axes[2].axhline(
    Ccrit, color="red", linestyle="--", linewidth=1.2,
    label=fr"$C_{{crit}}={Ccrit:.4f}$ mg/L"
)

# Shade intervals where C > Ccrit
axes[2].fill_between(
    t, Ccrit, C,
    where=(C > Ccrit),
    color="red", alpha=0.18, interpolate=True,
    label=r"$C>C_{crit}$"
)

# Mark each dose time
for td in dose_times:
    for ax in axes:
        ax.axvline(td, color="cornflowerblue",
                   linestyle=":", linewidth=0.7, alpha=0.6)

axes[2].set_title(
    r"(c) Drug concentration (shaded: $C>C_{crit}$, i.e. $Q(C)<0$)",
    fontsize=10
)
axes[2].set_ylabel("C (mg/L)")
axes[2].set_xlabel("Time (days)")
axes[2].set_xlim(0, 60)
axes[2].grid(True, alpha=0.25)
axes[2].legend(fontsize=8, loc="upper right")

plt.tight_layout()
plt.show()

# ============================================================
# Numerical values at selected days
# ============================================================

selected_days = np.array(
    [0, 7, 14, 21, 28, 35, 42, 49, 56, 60]
)
selected_indices = np.rint(selected_days / dt).astype(int)

print("Day       V (mm³)       E (10⁶ cells)      C (mg/L)")
for day, idx in zip(selected_days, selected_indices):
    print(
        f"{day:3d}   {V[idx]:12.4f}   "
        f"{E[idx]:14.6f}   {C[idx]:12.6f}"
    )