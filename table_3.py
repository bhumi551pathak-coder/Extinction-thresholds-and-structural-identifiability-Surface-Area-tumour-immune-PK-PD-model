df.to_csv("Table3_Local_Sensitivity.csv", index=False)

# =========================================================
# Plot 1: Sensitivity coefficients
# =========================================================

params = df["Parameter"]
S = df["Elasticity"]

fig, ax = plt.subplots(figsize=(10, 5.5))

bars = ax.bar(params, S)

ax.axhline(0, color="black", linewidth=0.8)
ax.set_xlabel("Model parameter")
ax.set_ylabel("Normalized sensitivity coefficient")
ax.set_title(
    r"Local Sensitivity of $V^*$ at $C^*=0$"
)
ax.grid(axis="y", alpha=0.3)

# Add numerical labels
for bar, value in zip(bars, S):
    if value >= 0:
        ypos = value + 0.06
        va = "bottom"
    else:
        ypos = value - 0.06
        va = "top"

    ax.text(
        bar.get_x() + bar.get_width()/2,
        ypos,
        f"{value:+.2f}",
        ha="center",
        va=va,
        fontsize=9
    )

plt.tight_layout()
plt.show()

# =========================================================
# Plot 2: Absolute sensitivity ranking
# =========================================================

ranking = df.loc[
    df["Elasticity"].abs().sort_values(ascending=False).index
].copy()

fig, ax = plt.subplots(figsize=(9, 5.5))

ax.barh(
    ranking["Parameter"],
    ranking["Elasticity"].abs()
)

ax.set_xlabel(r"Absolute sensitivity $|S|$")
ax.set_ylabel("Model parameter")
ax.set_title(r"Parameter Sensitivity Ranking for $V^*$")
ax.invert_yaxis()
ax.grid(axis="x", alpha=0.3)

plt.tight_layout()
plt.show()

print("\nSensitivity ranking:")
display(
    ranking[["Parameter", "Elasticity", "Impact"]]
    .reset_index(drop=True)
)

