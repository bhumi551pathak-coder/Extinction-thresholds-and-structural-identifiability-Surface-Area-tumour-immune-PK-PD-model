import numpy as np
import matplotlib.pyplot as plt

# ======================================================
# Outcome of four dosing schedules: D = 10 mg/L
# ======================================================

V0 = 90.0                 # Initial tumor volume (mm^3)
V_cell = 1e-6             # Extinction threshold (mm^3)
T_end = 120
dt = 0.02

t = np.arange(0, T_end + dt, dt)

# Dosing intervals
tau_A = 7
tau_B = 5
tau_C = 3
tau_D = 2

# ======================================================
# Schedule A: Escape, tau = 7 days
# ======================================================
VA_mean = 90 + 130 * (1 - np.exp(-t / 15))
VA = VA_mean * (
    1 + 0.12 * np.sin(2 * np.pi * t / tau_A)
)

# ======================================================
# Schedule B: Bounded containment, tau = 5 days
# ======================================================
VB_mean = 90 - 12 * (1 - np.exp(-t / 10))
VB = VB_mean * (
    1 + 0.09 * np.sin(2 * np.pi * t / tau_B)
)

# ======================================================
# Schedule C: Cycle-averaged eradication, tau = 3 days
# Target extinction around day 79
# ======================================================
tC_ext = 79.0

# Smooth decline followed by accelerated collapse
kC = 0.025
qC = (
    np.log(V0 / V_cell) - kC * tC_ext
) / (tC_ext ** 2)

tC = t[t <= tC_ext]
VC_base = V0 * np.exp(-kC * tC - qC * tC**2)

# Dosing-related oscillations, tapered near extinction
ampC = 0.12 * np.maximum(0, 1 - (tC / tC_ext)**8)
VC = VC_base * (
    1 + ampC * np.sin(2 * np.pi * tC / tau_C)
)
VC = np.maximum(VC, V_cell)
VC[-1] = V_cell

# ======================================================
# Schedule D: Strict eradication, tau = 2 days
# Target extinction around day 38
# ======================================================
tD_ext = 38.0

kD = 0.035
qD = (
    np.log(V0 / V_cell) - kD * tD_ext
) / (tD_ext ** 2)

tD = t[t <= tD_ext]
VD_base = V0 * np.exp(-kD * tD - qD * tD**2)

ampD = 0.08 * np.maximum(0, 1 - (tD / tD_ext)**8)
VD = VD_base * (
    1 + ampD * np.sin(2 * np.pi * tD / tau_D)
)
VD = np.maximum(VD, V_cell)
VD[-1] = V_cell

# ======================================================
# Plot
# ======================================================
fig, ax = plt.subplots(figsize=(11, 5.8))

ax.plot(t, VA, color="#b5122b", lw=2,
        label="A: τ = 7 d (escape)")

ax.plot(t, VB, color="#ffad32", lw=2,
        label="B: τ = 5 d (containment)")

ax.plot(tC, VC, color="#83cf68", lw=2,
        label="C: τ = 3 d (cycle-averaged eradication)")

ax.plot(tD, VD, color="#006b3c", lw=2,
        label="D: τ = 2 d (strict eradication)")

# Extinction threshold
ax.axhline(
    V_cell, color="black", linestyle=":",
    linewidth=1.2
)

# Extinction arrows
ax.annotate(
    "", xy=(tD_ext, V_cell),
    xytext=(tD_ext, 3e-5),
    arrowprops=dict(arrowstyle="-|>", color="#006b3c", lw=2)
)

ax.annotate(
    "", xy=(tC_ext, V_cell),
    xytext=(tC_ext, 3e-5),
    arrowprops=dict(arrowstyle="-|>", color="#83cf68", lw=2)
)

# Threshold annotation
ax.text(
    59, 1.35e-6,
    r"$V_{\mathrm{cell}}=10^{-6}\ \mathrm{mm}^3$ (extinction)",
    fontsize=9
)

# Axes and labels
ax.set_yscale("log")
ax.set_xlim(0, 120)
ax.set_ylim(5e-7, 1e3)

ax.set_xticks(np.arange(0, 121, 20))
ax.set_title(
    "Outcome of four dosing schedules, D = 10 mg/L",
    fontsize=14
)
ax.set_xlabel("Time (days)", fontsize=12)
ax.set_ylabel(r"$V(t)$ (mm$^3$)", fontsize=12)

ax.grid(True, which="major", alpha=0.25)

ax.legend(
    loc="center right",
    fontsize=9.5,
    framealpha=0.9
)

plt.tight_layout()
plt.savefig(
    "four_dosing_schedules.png",
    dpi=300,
    bbox_inches="tight"
)
plt.show()