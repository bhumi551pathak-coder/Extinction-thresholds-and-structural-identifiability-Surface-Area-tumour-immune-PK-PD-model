import pandas as pd
import matplotlib.pyplot as plt

# Table 2: Numerical Simulation of Tumor-Immune-Drug Dynamics

data = {
    "Day": [0, 7, 14, 21, 28, 35, 42, 49, 56, 60],
    "V (mm³)": [
        100.0000, 132.8068, 158.6427, 180.2314, 198.5378,
        214.0033, 226.9512, 237.6922, 246.5325, 209.1143
    ],
    "E (10⁶ cells)": [
        1.000000, 2.019662, 2.367621, 2.522303, 2.612673,
        2.675478, 2.722682, 2.759246, 2.787899, 2.783383
    ],
    "C (mg/L)": [
        10.00000, 10.07447, 10.07502, 10.07502, 10.07502,
        10.07502, 10.07502, 10.07502, 10.07502, 0.612663
    ]
}

df = pd.DataFrame(data)

# Display the table
print("Table 2: Numerical Simulation of Tumor–Immune–Drug Dynamics")
display(df.style
    .format({
        "V (mm³)": "{:.4f}",
        "E (10⁶ cells)": "{:.6f}",
        "C (mg/L)": "{:.6f}"
    })
    .set_caption(
        "Tumor volume, immune effector population, and drug concentration"
    )
    .hide(axis="index")
)

# Save table as CSV
df.to_csv("Table2_Numerical_Simulation.csv", index=False)

# Plot tumor volume
plt.figure(figsize=(8, 5))
plt.plot(data["Day"], data["V (mm³)"], "o-", linewidth=2)
plt.xlabel("Time (days)")
plt.ylabel("Tumor volume V (mm³)")
plt.title("Tumor Volume under Weekly Drug Treatment")
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

# Plot immune effector population
plt.figure(figsize=(8, 5))
plt.plot(data["Day"], data["E (10⁶ cells)"], "s-", linewidth=2)
plt.xlabel("Time (days)")
plt.ylabel("Immune effector population E (10⁶ cells)")
plt.title("Immune Effector Dynamics")
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

# Plot drug concentration
plt.figure(figsize=(8, 5))
plt.plot(data["Day"], data["C (mg/L)"], "^-", linewidth=2)
plt.xlabel("Time (days)")
plt.ylabel("Drug concentration C (mg/L)")
plt.title("Drug Concentration under Weekly Bolus Dosing")
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

print("CSV file saved as Table2_Numerical_Simulation.csv")